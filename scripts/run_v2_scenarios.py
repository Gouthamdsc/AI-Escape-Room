"""Replay every scenario against Version 2 and write docs/V2_TRANSCRIPTS.md.

Offline by default (engine text only). Add --llm to also use Gemini for narration.
Run from the repo root:  python scripts/run_v2_scenarios.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.scenarios import SCENARIOS, WALKTHROUGH  # noqa: E402
from v2 import engine, game  # noqa: E402


def main(use_llm):
    llm = None
    if use_llm:
        from common.llm import GeminiClient
        llm = GeminiClient()
    cfg = engine.load_config()
    lines = ["# Version 2 transcripts", "",
             f"Generated by `scripts/run_v2_scenarios.py` ({'with Gemini narration' if llm else 'offline, engine text only'}).", ""]
    all_runs = dict(SCENARIOS)
    all_runs["Full walkthrough (happy path)"] = WALKTHROUGH
    for title, messages in all_runs.items():
        state = engine.new_state(cfg)
        lines += [f"## {title}", ""]
        for m in messages:
            r = game.play_turn(cfg, state, m, llm=llm)
            lines += [f"**Player:** {m}", "",
                      f"**Game Master:** {r['reply']}", "",
                      f"`parsed: {r['action']}` `result: {r['outcome']['event'] if r['outcome'] else '-'}`", ""]
        f = state["flags"]
        lines += [f"*Final state:* inventory={state['inventory']}, drawer_open={f['drawer_open']}, "
                  f"safe_open={f['safe_open']}, door_unlocked={f['door_unlocked']}, escaped={f['escaped']}", ""]
    out = Path(__file__).resolve().parents[1] / "docs" / "V2_TRANSCRIPTS.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main("--llm" in sys.argv)
